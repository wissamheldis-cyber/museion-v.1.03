function buildSequentialEdges(): StoryboardEdge[] {
  const edges: StoryboardEdge[] = []
  for (let i = 0; i < DEMO_STORYBOARD_SCENES.length - 1; i++) {
    const current = DEMO_STORYBOARD_SCENES[i]
    const next = DEMO_STORYBOARD_SCENES[i + 1]
    if (current.sequenceId !== next.sequenceId) continue
    edges.push({
      id: `edge-${current.id}-${next.id}`,
      source: current.id,
      target: next.id,
      type: 'sequential',
    })
  }
  return edges
}

