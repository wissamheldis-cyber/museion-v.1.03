/** Disposition initiale du canvas : une ligne par séquence. */
export function defaultCanvasPosition(sequenceOrder: number, indexInSequence: number) {
  return { x: 80 + indexInSequence * 260, y: 80 + sequenceOrder * 220 }
}

export const DEMO_STORYBOARD_SCENES: StoryboardScene[] = SCENE_SEEDS.map((seed) => {
  const sequence = DEMO_SEQUENCES.find((s) => s.id === seed.sequenceId)!
  const siblings = SCENE_SEEDS.filter((s) => s.sequenceId === seed.sequenceId)
  const indexInSequence = siblings.findIndex((s) => s.id === seed.id)
  return {
    ...seed,
    projectId: PROJECT_ID,
    order: indexInSequence,
    canvasPosition: defaultCanvasPosition(sequence.order, indexInSequence),
  }
})

